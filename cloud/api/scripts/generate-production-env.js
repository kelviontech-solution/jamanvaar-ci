#!/usr/bin/env node
/**
 * Creates the secret part of a production environment file with fresh random values:
 *
 *   node scripts/generate-production-env.js [output-file] [--kid k3]
 *
 * The file is written OUTSIDE the repository (default: your home folder, never a synced folder such as OneDrive) and never printed.
 * The only thing printed is the licence PUBLIC key, which belongs in packages/config/src/license_keys.ts. Fill in the marked
 * placeholders (database, your console origins, SMTP, payment gateway) in the secrets store where the API runs; do not commit the file.
 */
const { randomBytes, generateKeyPairSync } = require('crypto');
const { existsSync, writeFileSync, chmodSync } = require('fs');
const os = require('os');
const path = require('path');

const args = process.argv.slice(2);
const kidIdx = args.indexOf('--kid');
const kid = kidIdx >= 0 ? args[kidIdx + 1] : 'k3';
const positional = args.filter((a, i) => !a.startsWith('--') && (kidIdx < 0 || i !== kidIdx + 1));
const out = path.resolve(positional[0] || path.join(os.homedir(), 'jamanvaar-production.env'));

if (/onedrive|dropbox|google drive/i.test(out) || out.startsWith(path.resolve(__dirname, '..', '..', '..'))) {
  console.error('Refusing to write secrets inside the repository or a synced folder. Choose a private location.');
  process.exit(1);
}
if (existsSync(out)) {
  console.error(`${out} already exists; refusing to overwrite it (delete it first to generate new secrets).`);
  process.exit(1);
}

const b64 = (n) => randomBytes(n).toString('base64');
const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
const pem = privateKey.export({ type: 'pkcs8', format: 'pem' }).toString();
const jwk = publicKey.export({ format: 'jwk' });

const lines = [
  '# Generated by scripts/generate-production-env.js. Keep private; never commit or sync.',
  'NODE_ENV=production',
  'PORT=4000',
  '# ---- FILL IN ----',
  'DATABASE_URL=postgresql://USER:PASSWORD@HOST:5432/DBNAME?schema=public',
  '# Comma-separated https origins of the consoles, e.g. https://admin.example.com (no localhost, no *)',
  'CORS_ALLOWED_ORIGINS=',
  '# Number of reverse proxies in front of the API (1 behind one load balancer)',
  'TRUST_PROXY=1',
  '# ---- GENERATED ----',
  `JWT_ACCESS_SECRET=${randomBytes(48).toString('base64url')}`,
  `QR_SESSION_SECRET=${randomBytes(48).toString('base64url')}`,
  `BACKUP_ENCRYPTION_KEY_B64=${b64(32)}`,
  `PAYMENT_CREDENTIAL_ENCRYPTION_KEY=${b64(32)}`,
  `LICENSE_SIGNING_KEY_ID=${kid}`,
  `LICENSE_SIGNING_PRIVATE_KEY_B64=${Buffer.from(pem).toString('base64')}`,
  '# Refuse voids/refunds that arrive without proof of which staff member did them (recommended once terminals are updated)',
  'REQUIRE_STAFF_SESSION=false',
  ''
];
writeFileSync(out, lines.join('\n'), { mode: 0o600 });
try { chmodSync(out, 0o600); } catch { /* best effort */ }

console.log(`Wrote ${out} (secrets not shown).`);
console.log(`Add this PUBLIC key to packages/config/src/license_keys.ts with kid '${kid}':`);
console.log(JSON.stringify({ kty: jwk.kty, crv: jwk.crv, x: jwk.x, y: jwk.y }));
